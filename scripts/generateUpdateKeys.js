// One-time setup for Ed25519 update signing.
//
//   node scripts/generateUpdateKeys.js
//
// Generates:
//   keys/update-signing-private.pem - private key (gitignored). Required by
//                                    prepareRelease for signing updates.
//   app/update-keys.js              - public key, committed and embedded in
//                                    the app for update verification.
//
// Existing keys are preserved. Regenerating them would invalidate signatures
// on previously released updates: installed clients only trust the public key
// they shipped with, so a lost/rotated private key means runtime updates stop
// working until users install a new binary. BACK UP the private key.
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const projectRoot = path.join(__dirname, "..");
const keysDir = path.join(projectRoot, "keys");
const privatePath = path.join(keysDir, "update-signing-private.pem");
const publicModulePath = path.join(projectRoot, "app", "update-keys.js");

const hasPrivate = fs.existsSync(privatePath);
const hasPublic = fs.existsSync(publicModulePath);

if (hasPrivate && hasPublic) {
  // Both exist: make sure they actually belong together.
  try {
    const privateKey = crypto.createPrivateKey(fs.readFileSync(privatePath, "utf8"));
    const derived = crypto.createPublicKey(privateKey).export({ type: "spki", format: "pem" });
    const embedded = require(publicModulePath).publicKey;
    if (derived.trim() !== String(embedded).trim()) {
      console.error("❌ keys/update-signing-private.pem does NOT match app/update-keys.js.");
      console.error("   Restore the correct private key (or the original app/update-keys.js). Nothing was changed.");
      process.exit(1);
    }
  } catch (err) {
    console.error(`❌ Could not validate the existing key pair: ${err.message}`);
    process.exit(1);
  }
  console.log("ℹ️  Update signing keys already exist and match - nothing done.");
  console.log(`   Private: ${privatePath}`);
  console.log(`   Public:  ${publicModulePath}`);
  process.exit(0);
}

if (hasPrivate !== hasPublic) {
  // Exactly one half exists: generating a new pair would silently orphan it.
  console.error("❌ Only one half of the signing key pair exists:");
  console.error(`   Private: ${hasPrivate ? "present" : "MISSING"}  (${privatePath})`);
  console.error(`   Public:  ${hasPublic ? "present" : "MISSING"}  (${publicModulePath})`);
  console.error("   Restore the missing file. If you really want a NEW pair (this breaks runtime updates");
  console.error("   for already installed versions), delete the remaining file and run this script again.");
  process.exit(1);
}

const { publicKey, privateKey } = crypto.generateKeyPairSync("ed25519", {
  privateKeyEncoding: { type: "pkcs8", format: "pem" },
  publicKeyEncoding: { type: "spki", format: "pem" },
});

fs.mkdirSync(keysDir, { recursive: true });
fs.writeFileSync(privatePath, privateKey, { mode: 0o600 });
fs.writeFileSync(
  publicModulePath,
  `// Public key used to verify runtime update signatures (ed25519).\n` +
    `// Generated by scripts/generateUpdateKeys.js - safe to commit; the private\n` +
    `// half lives in keys/update-signing-private.pem and must never be shared.\n` +
    `module.exports = { publicKey: ${JSON.stringify(publicKey)} };\n`,
);

console.log(`✅ Signing keypair generated`);
console.log(`   Private: ${privatePath}  (keep secret, used by prepareRelease.js)`);
console.log(`   Public:  ${publicModulePath}  (committed, embedded in the app)`);

// The private key must never be committed.
try {
  const gitignore = fs.readFileSync(path.join(projectRoot, ".gitignore"), "utf8");
  if (!/^\/?keys\/?\s*$/m.test(gitignore)) {
    console.warn("⚠️  .gitignore does not ignore keys/ - add a `keys/` line before committing!");
  }
} catch (_) {
  console.warn("⚠️  No .gitignore found - make sure keys/ is never committed.");
}
console.warn("⚠️  Back up keys/update-signing-private.pem (password manager / CI secret). If it is lost,");
console.warn("   runtime updates for already installed versions can no longer be signed.");
